# Definition for singly-linked list.
# class ListNode:
#     def __init__(self, val=0, next=None):
#         self.val = val
#         self.next = next
class Solution:
    def reverseList(self, head: Optional[ListNode]) -> Optional[ListNode]:
        #Declare temp, previous, next nodes
        temp=nex=head
        pre=None
        while temp :
            nex=temp.next
            temp.next=pre
            pre=temp
            temp=nex
        #Return pre
        return pre

        

