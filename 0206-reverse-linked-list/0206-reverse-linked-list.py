# Definition for singly-linked list.
# class ListNode:
#     def __init__(self, val=0, next=None):
#         self.val = val
#         self.next = next
class Solution:
    def reverseList(self, head: ListNode | None) -> ListNode | None:
        #Declare temp, prev, nex nodes
        temp=nex=head
        prev=None
        
        while temp :
            nex=temp.next
            temp.next=prev
            prev=temp
            temp=nex
        
        #Return prev
        return prev
        

